import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const staticRoot = realpathSync(resolve(root, 'static'));
const inputPath = resolve(staticRoot, 'kiosk-config.json');
const outputPath = resolve(root, 'portable/configuration.generated.ts');
const maxConfigurationBytes = 32 * 1024;
const maxLogoBytes = 256 * 1024;
const logoPattern = /^[a-z0-9][a-z0-9._-]*\.(png|webp|svg)$/i;

function fail(message) {
  throw new Error(`Portable configuration: ${message}`);
}

const source = readFileSync(inputPath);
if (source.byteLength > maxConfigurationBytes) fail('kiosk-config.json must be at most 32 KiB');
let configuration;
try {
  configuration = JSON.parse(source.toString('utf8'));
} catch (error) {
  fail(`kiosk-config.json is not valid JSON (${error.message})`);
}

let embeddedOrganizationLogo;
const organizationLogo = configuration?.organizationLogo;
if (organizationLogo !== undefined) {
  if (
    typeof organizationLogo !== 'string' ||
    organizationLogo.length > 120 ||
    !logoPattern.test(organizationLogo)
  ) {
    fail('organizationLogo must be a local PNG, WebP, or SVG filename');
  }
  const logoPath = resolve(staticRoot, organizationLogo);
  if (!existsSync(logoPath)) fail(`organizationLogo file does not exist: ${organizationLogo}`);
  const resolvedLogoPath = realpathSync(logoPath);
  if (!resolvedLogoPath.startsWith(`${staticRoot}/`)) {
    fail('organizationLogo symlink must resolve inside static/');
  }
  const logo = readFileSync(resolvedLogoPath);
  if (logo.byteLength > maxLogoBytes) fail('organizationLogo must be at most 256 KiB');
  const extension = extname(organizationLogo).toLowerCase();
  const png =
    logo.length >= 8 && logo.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
  const webp =
    logo.length >= 12 &&
    logo.subarray(0, 4).toString() === 'RIFF' &&
    logo.subarray(8, 12).toString() === 'WEBP';
  let mime;
  if (extension === '.png' && png) mime = 'image/png';
  else if (extension === '.webp' && webp) mime = 'image/webp';
  else if (extension === '.svg') {
    let svg;
    try {
      svg = new TextDecoder('utf-8', { fatal: true }).decode(logo);
    } catch {
      fail('SVG organizationLogo must be valid UTF-8');
    }
    if (!/<svg(?:\s|>)/i.test(svg.slice(0, 4096))) {
      fail('SVG organizationLogo must contain an SVG root element near the start');
    }
    mime = 'image/svg+xml';
  } else fail('organizationLogo content does not match its filename extension');
  embeddedOrganizationLogo = `data:${mime};base64,${logo.toString('base64')}`;
}

function scriptSafeJson(value) {
  const serialized = JSON.stringify(value);
  if (serialized === undefined) return 'undefined';
  return serialized.replace(
    /[<>&\u2028\u2029]/gu,
    (character) => `\\u${character.codePointAt(0).toString(16).padStart(4, '0')}`,
  );
}

mkdirSync(resolve(root, 'portable'), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/prepare-portable-configuration.mjs; do not edit.\nexport const configuration: unknown = ${scriptSafeJson(configuration)};\nexport const embeddedOrganizationLogo: string | undefined = ${scriptSafeJson(embeddedOrganizationLogo)};\n`,
);
console.log(
  embeddedOrganizationLogo
    ? `Prepared portable configuration with ${organizationLogo}`
    : 'Prepared portable configuration without an organisation logo',
);
