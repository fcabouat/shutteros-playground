import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const staticRoot = realpathSync(resolve(root, 'static'));
const inputPath = resolve(staticRoot, 'kiosk-config.json');
const outputPath = resolve(root, 'portable/configuration.generated.ts');
const maxConfigurationBytes = 32 * 1024;
const maxLogoBytes = 256 * 1024;
const logoPattern = /^[a-z0-9][a-z0-9._-]*\.(png|webp|svg)$/i;

function fail(message) {
  throw new Error(`Portable configuration: ${message}`);
}

const source = readFileSync(inputPath);
if (source.byteLength > maxConfigurationBytes) fail('kiosk-config.json must be at most 32 KiB');
let configuration;
try {
  configuration = JSON.parse(source.toString('utf8'));
} catch (error) {
  fail(`kiosk-config.json is not valid JSON (${error.message})`);
}

function embedStaticLogo(reference, key) {
  if (typeof reference !== 'string' || reference.length > 120 || !logoPattern.test(reference)) {
    fail(`${key} must be a local PNG, WebP, or SVG filename`);
  }
  const logoPath = resolve(staticRoot, reference);
  if (!existsSync(logoPath)) fail(`${key} file does not exist: ${reference}`);
  const resolvedLogoPath = realpathSync(logoPath);
  if (!resolvedLogoPath.startsWith(`${staticRoot}/`)) {
    fail(`${key} symlink must resolve inside static/`);
  }
  const logo = readFileSync(resolvedLogoPath);
  if (logo.byteLength > maxLogoBytes) fail(`${key} must be at most 256 KiB`);
  const extension = extname(reference).toLowerCase();
  const png =
    logo.length >= 8 && logo.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
  const webp =
    logo.length >= 12 &&
    logo.subarray(0, 4).toString() === 'RIFF' &&
    logo.subarray(8, 12).toString() === 'WEBP';
  let mime;
  if (extension === '.png' && png) mime = 'image/png';
  else if (extension === '.webp' && webp) mime = 'image/webp';
  else if (extension === '.svg') {
    // This is a format check, not SVG sanitization. The publisher supplies the file,
    // and OrganizationBrand renders it as an image, not inline SVG or an embedded document.
    let svg;
    try {
      svg = new TextDecoder('utf-8', { fatal: true }).decode(logo);
    } catch {
      fail(`SVG ${key} must be valid UTF-8`);
    }
    if (!/<svg(?:\s|>)/i.test(svg.slice(0, 4096))) {
      fail(`SVG ${key} must contain an SVG root element near the start`);
    }
    mime = 'image/svg+xml';
  } else fail(`${key} content does not match its filename extension`);
  return `data:${mime};base64,${logo.toString('base64')}`;
}

// Preserve the versioned JSON as unknown for the runtime decoder. Only the asset
// reference needs build-time resolution; the data URL travels as a separate prop so
// the external contract can keep rejecting URLs in organizationLogo.
const organizationLogo = configuration?.organizationLogo;
const partnerOrganizationLogo = configuration?.partnerOrganizationLogo;
if (
  partnerOrganizationLogo !== undefined &&
  (typeof configuration?.partnerOrganizationName !== 'string' ||
    configuration.partnerOrganizationName.trim().length === 0)
) {
  fail('partnerOrganizationLogo requires partnerOrganizationName');
}
const embeddedOrganizationLogo =
  organizationLogo === undefined
    ? undefined
    : embedStaticLogo(organizationLogo, 'organizationLogo');
const embeddedPartnerOrganizationLogo =
  partnerOrganizationLogo === undefined
    ? undefined
    : embedStaticLogo(partnerOrganizationLogo, 'partnerOrganizationLogo');

// The generated module ends up inside a script element in the portable artifact.
// Escape HTML delimiters as well as JSON syntax; portable-configuration.test.ts
// checks that decoded values are preserved without literal script termination.
function scriptSafeJson(value) {
  const serialized = JSON.stringify(value);
  if (serialized === undefined) return 'undefined';
  return serialized.replace(
    /[<>&\u2028\u2029]/gu,
    (character) => `\\u${character.codePointAt(0).toString(16).padStart(4, '0')}`,
  );
}

mkdirSync(resolve(root, 'portable'), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/prepare-portable-configuration.mjs; do not edit.\nexport const configuration: unknown = ${scriptSafeJson(configuration)};\nexport const embeddedOrganizationLogo: string | undefined = ${scriptSafeJson(embeddedOrganizationLogo)};\nexport const embeddedPartnerOrganizationLogo: string | undefined = ${scriptSafeJson(embeddedPartnerOrganizationLogo)};\n`,
);
console.log(
  embeddedOrganizationLogo || embeddedPartnerOrganizationLogo
    ? `Prepared portable configuration with ${[organizationLogo, partnerOrganizationLogo]
        .filter(Boolean)
        .join(', ')}`
    : 'Prepared portable configuration without an organisation logo',
);
